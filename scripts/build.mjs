import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const core = (await read('src/core.js')).replaceAll('export ', '');
const calendar = (await read('src/calendar.js')).replaceAll('export ', '');
const client = (await read('src/client.js')).replace(/^import .*;\n/gm, '');
await mkdir(new URL('lib/', root), { recursive: true });
await writeFile(new URL('lib/client.js', root), '// Generated by node scripts/build.mjs; edit src instead.\n(() => {\n' + core + '\n' + calendar + '\n' + client + '\n})();\n');
